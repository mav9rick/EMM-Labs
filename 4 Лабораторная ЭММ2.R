# Задание 1: Реализация последовательности банковского счета {B_n}
N <- 200          # количество шагов
r <- 0.01         # процентная ставка
B <- numeric(N + 1)  # вектор для хранения значений B_n (от B_0 до B_200)
B[1] <- 1         # начальное значение B_0 = 1

# Вычисление значений B_n
for (n in 1:N) {
  B[n + 1] <- (1 + r) * B[n]
}

# Построение графика банковского счета
plot(0:N, B, type = "l", col = "blue", xlab = "n", ylab = "B_n", 
     main = "Рост банковского счета при r = 0.01")
cat("B_0:", B[1], "\nB_200:", B[201], "\n")

# Задание 2: Реализация случайного процесса акций {S_n}
S0 <- 1           # начальная цена акции
a <- -0.3         # нижняя доходность
b <- 0.8          # верхняя доходность
p <- 0.4          # вероятность роста
S <- numeric(N + 1)  # вектор для хранения значений S_n
S[1] <- S0        # начальное значение S_0 = 1

set.seed(123)     # для воспроизводимости
rho <- rbinom(N, 1, p)  # бернуллиевские случайные величины
rho <- ifelse(rho == 1, b, a)  # преобразование в a или b

# Вычисление значений S_n
for (n in 1:N) {
  S[n + 1] <- (1 + rho[n]) * S[n]
}

# Построение графика одной траектории цены акции
plot(0:N, S, type = "l", col = "red", xlab = "n", ylab = "S_n", 
     main = "Одна траектория цены акции")
cat("S_0:", S[1], "\nS_200:", S[201], "\n")


# Задание 3: Расчет справедливой цены call-опциона
S0 <- 100         # начальная цена акции
N <- 10           # количество шагов
a <- -0.3         # нижняя доходность
b <- 0.8          # верхняя доходность
r <- 0.2          # процентная ставка
K <- 100          # цена исполнения (strike price)

# Вычисление \bar{p}
p_bar <- (r - a) / (b - a)

# Вычисление p^*
p_star <- (1 + b) / (1 + r) * p_bar

# Вычисление K_0
ln_term1 <- log(K / (S0 * (1 + a)^N))
ln_term2 <- log((1 + b) / (1 + a))
K0 <- 1 + floor(ln_term1 / ln_term2)

# Расчет справедливой цены C_N
if (K0 > N) {
  C_N <- 0
} else {
  # Вычисление B(K0, N; p^*) — хвост биномиального распределения
  B_p_star <- 1 - pbinom(K0 - 1, N, p_star)
  
  # Вычисление B(K0, N; \bar{p})
  B_p_bar <- 1 - pbinom(K0 - 1, N, p_bar)
  
  # Вычисление справедливой цены call-опциона
  C_N <- S0 * B_p_star - K * (1 + r)^(-N) * B_p_bar
}

# Вывод результата
cat("Справедливая цена call-опциона:", C_N, "\n")
